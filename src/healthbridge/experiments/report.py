"""Render fault-injection results (results.json) as a Markdown report."""
from __future__ import annotations

from collections import Counter, defaultdict

from healthbridge.core.build import (
    CONFLICT_TOLERANCE,
    DEPENDENCE_MIN_SHARE,
    DEPENDENCE_MIN_SHARED,
    DEPENDENCE_TOLERANCE,
    GROUP_DISAGREEMENT_TOLERANCE,
)
from healthbridge.core.outliers import OUTLIER_REL_FLOOR, OUTLIER_Z
from healthbridge.experiments.evaluate import wilson

FAULT_ORDER = ["missing_value", "unparseable_value", "out_of_range", "duplicate",
               "country_recoverable", "country_invalid", "date_noncanonical", "date_unparseable",
               "categorical_invalid", "value_change", "schema_rename_required",
               "schema_drop_required", "schema_add_unexpected"]
DESCRIPTION = {
    "missing_value": "value blanked", "unparseable_value": "value replaced by text (n/a, -, ...)",
    "out_of_range": "value above the plausible maximum or negative", "duplicate": "exact copy of a row appended",
    "country_recoverable": "country written as lowercase, padded, ISO2, name or known alias",
    "country_invalid": "country replaced by an unknown or region code",
    "date_noncanonical": "year written as 2019-06 or 2019.0", "date_unparseable": "year written as 19, FY2019, N/A, June 2019",
    "categorical_invalid": "sex, wealth or residence code outside the vocabulary",
    "value_change": "value changed by a known relative amount (see section 3)",
    "schema_rename_required": "required column renamed (file level)", "schema_drop_required": "required column removed (file level)",
    "schema_add_unexpected": "unknown extra column added (file level)",
}
MECHANISMS = ["rejected:no_value", "rejected:unparseable_value", "rejected:out_of_range",
              "rejected:exact_duplicate", "rejected:unknown_country", "rejected:invalid_year",
              "rejected:unmapped_vocabulary", "flagged:noncanonical_period", "flagged:temporal_outlier",
              "flagged:within_group_disagreement", "flagged:conflict", "flagged:bounds_violation"]


def _pct(x: float, digits: int = 1) -> str:
    return f"{100 * x:.{digits}f}%"


def _rate(successes: int, n: int) -> str:
    if n == 0:
        return "n/a"
    lo, hi = wilson(successes, n)
    return f"{_pct(successes / n)} ({_pct(lo, 0)}-{_pct(hi, 0)})"


def _results(data: dict, passes: tuple[str, ...] | None = None) -> list[dict]:
    return [r for run in data["runs"] if passes is None or run["pass"] in passes for r in run["results"]]


def _group(results: list[dict], key) -> dict:
    out: dict = defaultdict(list)
    for r in results:
        out[key(r)].append(r)
    return out


def render_report(data: dict) -> str:
    results = _results(data)
    by_type = _group(results, lambda r: r["fault_type"])
    runs = data["runs"]
    seeds = len(data["seeds"])
    lines = [
        "# Fault-injection experiment: how well do the pipeline's checks detect known errors?",
        "",
        (f"Clean snapshot `{data['clean_run_id']}`; {seeds} seeds; {len(results):,} injected faults in "
        f"{len(runs)} corrupted snapshots. Generated by `python -m healthbridge.experiments report`."),
        "",
        "## Method",
        "",
        ("1. Take the real pipeline's output for the clean snapshot. Rows that were loaded, selected "
        f"for the default surface, unflagged and in cells without a source conflict form the "
        f"**clean universe** ({data['universe_rows']:,} of {data['pool_rows']:,} analysis rows)."),
        ("2. Write a *copy* of the raw snapshot with faults injected at known positions, using a "
        "fixed seed. The copy is a valid snapshot, so the real pipeline (`load` then `build`) runs "
        "on it unchanged. Each row gets at most one fault; rows are modified in place or appended, "
        "so every fault keeps a known (file, row) identity."),
        ("3. Read what the pipeline did with each injected row: rejected with a reason, flagged, "
        "loaded unchanged (**recovered**) or loaded wrong and unflagged (**silent**)."),
        ("4. A fault is *handled correctly* when the outcome is in its expected set. Rates are "
        "pooled over seeds with 95% Wilson intervals."),
        "",
        ("Three passes are run separately so faults cannot interfere: *validity* (nine fault types, "
        f"{data['n_validity_per_type']} per type per seed), *magnitude* (one value changed by a "
        f"known relative amount, {data['n_magnitude_per_level']} per level per seed, at most one per "
        "series and cell) and *schema* (file-level)."),
        "",
        ("Pre-set parameters (fixed before the experiment, not tuned on it): temporal outlier = modified "
        f"z-score > {OUTLIER_Z} and deviation > {_pct(OUTLIER_REL_FLOOR, 0)} of the neighbour median; "
        f"source disagreement inside an evidence group > {_pct(GROUP_DISAGREEMENT_TOLERANCE, 0)}; "
        f"independent evidence groups conflict > {_pct(CONFLICT_TOLERANCE, 0)}; dependence = at least "
        f"{DEPENDENCE_MIN_SHARED} shared country-years with at least {_pct(DEPENDENCE_MIN_SHARE, 0)} "
        f"within {_pct(DEPENDENCE_TOLERANCE, 0)}."),
        "",
        "## 1. Detection by fault type",
        "",
        ("*Handled correctly* = outcome in the expected set. *Handled differently* = caught, but by "
        "another mechanism than expected (for example rejected where repair was expected). *Silent* = "
        "loaded wrong and unflagged."),
        "",
        "| Fault | What was injected | Injected | Handled correctly | Handled differently | Silent |",
        "|---|---|---|---|---|---|",
    ]
    for ft in FAULT_ORDER:
        rs = by_type.get(ft)
        if not rs:
            continue
        n = len(rs)
        correct = sum(r["correct"] for r in rs)
        silent = sum(r["silent"] for r in rs)
        lines.append(f"| {ft} | {DESCRIPTION[ft]} | {n:,} | {_rate(correct, n)} | "
                     f"{_pct((n - correct - silent) / n)} | {_rate(silent, n)} |")

    lines += ["", "## 2. Variants", "",
              "| Fault | Variant | Injected | Handled correctly | Most common outcome |", "|---|---|---|---|---|"]
    for ft in ("country_recoverable", "country_invalid", "date_noncanonical", "date_unparseable",
               "categorical_invalid", "unparseable_value", "out_of_range"):
        for variant, rs in sorted(_group(by_type.get(ft, []), lambda r: r["variant"]).items()):
            n = len(rs)
            top = Counter(r["labels"][0] for r in rs).most_common(1)[0][0]
            lines.append(f"| {ft} | {variant} | {n:,} | {_rate(sum(r['correct'] for r in rs), n)} | {top} |")

    changes = by_type.get("value_change", [])
    lines += [
        "", "## 3. Value corruption by magnitude", "",
        ("One value is changed by the stated relative amount (±). *Outlier* = flagged by the temporal "
        "check; *Disagreement* = flagged because sources of one evidence group differ by more than "
        f"{_pct(GROUP_DISAGREEMENT_TOLERANCE, 0)}; either counts as detection."),
        "",
        "| Change | Injected | Detected | Outlier check | Disagreement check | Silent |", "|---|---|---|---|---|---|"]
    magnitudes = sorted(_group(changes, lambda r: r["variant"]).items(), key=lambda kv: float(kv[0].rstrip("%")))
    for variant, rs in magnitudes:
        n = len(rs)
        has = lambda label, rs=rs: sum(label in r["labels"] for r in rs)
        lines.append(f"| {variant} | {n:,} | {_rate(sum(r['correct'] for r in rs), n)} | "
                     f"{_rate(has('flagged:temporal_outlier'), n)} | "
                     f"{_rate(has('flagged:within_group_disagreement'), n)} | {_rate(sum(r['silent'] for r in rs), n)} |")
    large = [r for r in changes if float(r["variant"].rstrip("%")) >= 50]
    lines += ["", ("Detection of **large changes (50% or more)** by the context available to the checks "
              "(the outlier check needs at least 3 neighbouring observations; the disagreement check "
              "needs another source in the same group). Small changes are left out so that context "
              "is not confounded with magnitude:"), "",
              "| Context | Injected | Detected |", "|---|---|---|"]
    strata = _group(large, lambda r: (r["n_neighbors"] >= 3, r["cell_members"] >= 2))
    names = {(True, True): "series context and another source", (True, False): "series context only",
             (False, True): "another source only"}
    for key, label in names.items():
        rs = strata.get(key, [])
        if rs:
            lines.append(f"| {label} | {len(rs):,} | {_rate(sum(r['correct'] for r in rs), len(rs))} |")

    lines += [
        "", "## 4. Naive loader vs pipeline", "",
        ("The naive loader parses each row, joins on the exact ISO3 string and drops nulls, with no "
        "validation. *Accepted wrong* means the corrupted row would enter an analysis with wrong "
        "content (or, for duplicates, be counted twice). The pipeline column is the share of faults "
        "that ended silent. Categorical faults are not compared because a loader that ignores "
        "dimensions never uses them."), "",
        "| Fault | Naive: accepted wrong | Naive: dropped | Naive: accepted correct | Pipeline: silent |",
        "|---|---|---|---|---|"]
    for ft in FAULT_ORDER:
        rs = [r for r in by_type.get(ft, []) if r["naive"] is not None]
        if not rs:
            continue
        counts = Counter(r["naive"] for r in rs)
        n = len(rs)
        lines.append(f"| {ft} | {_pct(counts['accepted_wrong'] / n)} | {_pct(counts['dropped'] / n)} | "
                     f"{_pct(counts['accepted_correct'] / n)} | {_pct(sum(r['silent'] for r in rs) / n)} |")

    tp = Counter(label for r in results for label in r["labels"] if label in MECHANISMS)
    fp: Counter = Counter()
    universe_total = 0
    for run in runs:
        if run["pass"] != "schema":
            fp.update(run["false_positives"])
            universe_total += data["universe_rows"]
    clean = data["clean_alerts"]
    clean_rate = {
        "flagged:temporal_outlier": clean["temporal_outlier"] / clean["selected_rows"],
        "flagged:bounds_violation": clean["bounds_violation"] / clean["selected_rows"],
        "flagged:noncanonical_period": clean["noncanonical_period"] / clean["selected_rows"],
        "flagged:within_group_disagreement": clean["within_group_disagreement"] / clean["reconciled_cells"],
        "flagged:conflict": clean["conflict"] / clean["reconciled_cells"],
    }
    lines += [
        "", "## 5. Precision and false alarms", "",
        ("*True positives* are injected faults the mechanism fired on. *False positives* are alerts "
        "on rows (or cells) from the clean universe that were not touched. *Alert rate on clean "
        "data* is how often the check fires on the unmodified snapshot, including real events; "
        "those alerts are unlabeled, so they are context, not counted as errors. Rule-based "
        "validity checks have no alert rate on clean data: a clean row passes them by definition."), "",
        "| Mechanism | True positives | False positives | Precision | Alert rate on clean data |",
        "|---|---|---|---|---|"]
    for m in MECHANISMS:
        if tp[m] == 0 and fp[m] == 0:
            continue
        precision = _pct(tp[m] / (tp[m] + fp[m])) if tp[m] + fp[m] else "n/a"
        rate = _pct(clean_rate[m], 2) if m in clean_rate else "n/a (rule-based)"
        lines.append(f"| {m} | {tp[m]:,} | {fp[m]:,} | {precision} | {rate} |")
    lines += ["", (f"False positives were counted over {universe_total:,} clean-universe row evaluations "
              f"({len([r for r in runs if r['pass'] != 'schema'])} pipeline runs).")]
    assessable = data["assessable_by_outlier_check"] / data["pool_rows"]
    lines += [(f"{_pct(assessable)} of analysis rows have enough neighbouring observations for the outlier "
              "check to assess them at all; the rest rely on cross-source comparison.")]

    schema = [r for r in results if r["fault_type"].startswith("schema_")]
    lines += ["", "## 6. Schema faults (file level)", "",
              "| Fault | Source | Files | Handled correctly |", "|---|---|---|---|"]
    for (ft, source), rs in sorted(_group(schema, lambda r: (r["fault_type"], r["source"])).items()):
        lines.append(f"| {ft} | {source} | {len(rs)} | {_rate(sum(r['correct'] for r in rs), len(rs))} |")

    row_level = [r for r in results if not r["fault_type"].startswith("schema_")]
    detected = [r for r in row_level if not r["silent"] and r["labels"] != ["lost"]]
    below = sorted(((ft, sum(r["correct"] for r in rs) / len(rs)) for ft, rs in by_type.items()
                    if sum(r["correct"] for r in rs) < len(rs)), key=lambda x: x[1])
    weak = ("Fault types below 100% correct handling: "
            + "; ".join(f"{ft} ({_pct(rate)})" for ft, rate in below) + "."
            if below else "Every fault type was handled correctly in every case.")
    lines += [
        "", "## 7. Summary", "",
        (f"- Of {len(row_level):,} row-level faults, {_pct(len(detected) / len(row_level))} were rejected, "
        "flagged or repaired; the rest got through silently."),
        f"- {weak}",
        "", "## 8. Limitations and threats to validity", "",
        ("- Injected faults are synthetic proxies. Real errors may be subtler, correlated, or of "
        "kinds not injected here."),
        ("- Valid-looking corruptions are undetectable by design and are not counted: a country code "
        "swapped for another valid country, a sex code swapped for another valid code, or a small "
        "change to a value in a series with no context and no second source."),
        ("- Rates depend on the injection rates and magnitudes chosen, and on one snapshot. They "
        "describe this pipeline on this data, not data quality in general."),
        ("- Check parameters were fixed in advance, but they are judgements. Precision of the "
        "statistical checks depends on real events in the data being counted as alerts, not errors."),
        ("- World Bank values keep no raw text in staging, so an unparseable World Bank value is "
        "reported as missing; this is expected and is why its expected outcome differs."),
        "- The naive loader is deliberately minimal; a careful analyst would catch more by hand.",
        "",
    ]
    return "\n".join(lines)
